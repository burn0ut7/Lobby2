"""Developer-only source generation; no Python or executable ships at runtime.

Keep existing definitions authoritative for fields, defaults and gameplay behavior.
Only the four condition containers replace nested attributes with hierarchy children.
Review generated Enforce code and compile in Workbench after running this file.
"""
import pathlib
import re

ROOT = pathlib.Path(__file__).resolve().parents[1] / "scripts/Game/MissionFramework"
OUTPUT = ROOT / "Authoring"
CLASSES = {}
TITLES = {}
for path in sorted(ROOT.glob("*.c")):
    if path.name.endswith("Entity.c") or path.name == "GC_MissionEntityAdapters.c":
        continue
    source = path.read_text(encoding="utf-8-sig")
    for match in re.finditer(r'\[BaseContainerProps\(\), BaseContainerCustomStringTitleField\("([^"]+)"\)\]\s*class (GC_\w+)', source):
        TITLES[match[2]] = match[1]
    for match in re.finditer(r"(?m)^class (GC_\w+)(?:\s*:\s*(\w+))?\s*\{", source):
        start = match.end()
        depth = 1
        end = None
        for token in re.finditer(r'"(?:\\.|[^"\\])*"|//[^\n]*|/\*.*?\*/|[{}]', source[start:], re.S):
            if token.group() == "{":
                depth += 1
            elif token.group() == "}":
                depth -= 1
            if depth == 0:
                end = start + token.start()
                break
        assert end is not None, path
        body = source[start:end]
        fields = []
        for field in re.finditer(r"(\[Attribute\(.*?\)\])\s*\n\s*((?:protected\s+)?(?:ref\s+)?[\w<> ,]+?)\s+(m_\w+)\s*;", body, re.S):
            fields.append((field[1], field[2], field[3]))
        assert body.count("[Attribute(") == len(fields), f"Unsupported attribute syntax: {match[1]}"
        CLASSES[match[1]] = (match[2], fields)


def inherits(name, base):
    return name == base or (name in CLASSES and inherits(CLASSES[name][0], base))


def fields(name):
    parent, own = CLASSES[name]
    result = (fields(parent) if parent in CLASSES else []) + own
    assert len({field[2] for field in result}) == len(result), name
    return result


# Internal runtime helpers are not authoring types. These bases only prompt for a type.
BASES = {"GC_MissionCondition", "GC_MissionAction", "GC_AreaCondition"}
targets = {name: title for name, title in TITLES.items() if name not in BASES
           and (inherits(name, "GC_MissionCondition") or inherits(name, "GC_MissionAction"))}
assert len(targets) == 39, "Review catalog coverage when adding/removing definition types."
targets["GC_MissionFlag"] = "Mission Flag"
CONTAINERS = {"GC_ConditionGroup", "GC_HeldCondition", "GC_CaptureCondition", "GC_MissionFlag"}
OUTPUT.mkdir(exist_ok=True)
separator = "\t//" + "-" * 96
for name, title in targets.items():
    flag = name == "GC_MissionFlag"
    condition = inherits(name, "GC_MissionCondition")
    base = "GC_MissionCondition" if condition else "GC_MissionAction"
    entity_base = "GC_MissionAuthoringEntity" if flag else base + "Entity"
    entity = name + "Entity"
    entries = fields(name)
    own_fields = [field for field in entries if field[2] not in ("m_Condition", "m_aConditions")]
    assert len(entries) == len(own_fields) + (1 if name in CONTAINERS else 0), name
    category = "" if flag else "/Conditions" if condition else "/Actions"
    out = ["//! Generated by tools/generate_mission_entities.py. Gameplay stays in the definition class.",
           f'[EntityEditorProps(category: "GameScripted/Mission Framework{category}", description: "{title}")]',
           f"class {entity}Class : {entity_base}Class", "{", "}", "",
           f"class {entity} : {entity_base}", "{"]
    for attr, kind, field in own_fields:
        attr = re.sub(r', enums: \{ParamEnum\("", "", "rst-choices:[^"]+"\)\}', "", attr)
        if field in ("m_sFlag", "m_sFaction", "m_sWinningFaction"):
            attr = attr.replace("UIWidgets.EditBox", "UIWidgets.EditComboBox")
        out += ["\t" + attr, "\t" + kind.removeprefix("protected ") + " " + field + ";"]
    method = "BuildFlag" if flag else "BuildCondition" if condition else "BuildAction"
    returned_type = "GC_MissionFlag" if flag else base
    override = "" if flag else "override "
    out += ["", separator, f"\t{override}{returned_type} {method}(out string error)", "\t{"]
    if name in CONTAINERS:
        out += ["\t\tarray<ref GC_MissionCondition> conditions = {};",
                "\t\tif (!ReadChildren(conditions, null, error))", "\t\t\treturn null;"]
        if name != "GC_ConditionGroup":
            test = "conditions.Count() > 1" if flag else "conditions.Count() != 1"
            out += [f"\t\tif ({test})", "\t\t{",
                    '\t\t\terror = "' + ("Mission Flag accepts at most one condition child: " if flag else "This node needs exactly one condition child: ") + '" + GetName();',
                    "\t\t\treturn null;", "\t\t}", "\t\tGC_MissionCondition childCondition;",
                    "\t\tif (!conditions.IsEmpty())", "\t\t\tchildCondition = conditions[0];"]
    else:
        out += ["\t\tif (GetChildren())", "\t\t{",
                '\t\t\terror = "This mission node does not accept children: " + GetName();',
                "\t\t\treturn null;", "\t\t}"]
    args = ["conditions" if field == "m_aConditions" else "childCondition" if field == "m_Condition" else field
            for _, _, field in entries]
    assert all(not kind.startswith("protected ") for _, kind, _ in entries), name
    out += [f"\t\t{name} definition = new {name}();"]
    out += [f"\t\tdefinition.{field} = {value};" for (_, _, field), value in zip(entries, args)]
    out += ["\t\treturn definition;", "\t}", "}", ""]
    (OUTPUT / (entity + ".c")).write_text("\n".join(out), encoding="utf-8")
print(f"Generated {len(targets)} adapters: 12 conditions, 27 actions, 1 optional flag definition.")
